//! Flows: declarative, session-scoped funnel instrumentation.
//!
//! A flow is a named task type declared in `flows.yaml`. glean_parser turns
//! each declaration into a [`FlowDefinition`], which the language binding
//! passes to Glean through its configuration. At init, core inverts those
//! definitions into a [`FlowRegistry`], keyed by event, so the recording path
//! resolves everything it needs about an event with a single lookup.

use std::collections::{BTreeMap, HashMap};

use malloc_size_of_derive::MallocSizeOf;
use serde::{Deserialize, Serialize};

use crate::common_metric_data::CommonMetricDataInternal;
use crate::Glean;

/// The role an event plays in a flow.
#[derive(Debug, Clone, Copy, PartialEq, Eq, MallocSizeOf)]
pub enum FlowRole {
    /// Recording the event opens an instance of the flow, if none is active.
    Start,
    /// Recording the event closes the active instance of the flow, if any.
    End,
    /// The event belongs to the flow but does not open or close it.
    Member,
}

/// A flow definition, as generated by glean_parser from `flows.yaml`.
#[derive(Debug, Clone, PartialEq, Eq, MallocSizeOf)]
pub struct FlowDefinition {
    /// The flow's name.
    pub name: String,
    /// Each member event's identifier (`category.name`), mapped to the role it
    /// plays in this flow.
    pub events: HashMap<String, FlowRole>,
    /// How long an instance may stay open before it is closed with
    /// `reason: timeout`, in milliseconds. `None` means it never times out.
    pub auto_close_timeout_ms: Option<u64>,
    /// Whether the flow ships disabled.
    pub disabled: bool,
}

/// An active flow instance an event belongs to, as attached to the recorded event.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize, MallocSizeOf)]
pub struct FlowEntry {
    /// The flow's name.
    pub name: String,
    /// The instance's sequence number within the session, starting at 0.
    pub seq: u64,
}

/// Identifies a registered flow.
///
/// Flows are numbered in name order, so sorting by `FlowId` sorts by name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, MallocSizeOf)]
pub(crate) struct FlowId(usize);

/// A flow as held by the registry.
#[derive(Debug, MallocSizeOf)]
pub(crate) struct RegisteredFlow {
    pub(crate) name: String,
    pub(crate) auto_close_timeout_ms: Option<u64>,
    pub(crate) disabled: bool,
}

/// The flows a single event takes part in.
///
/// Each list is in name order.
#[derive(Debug, Default, PartialEq, Eq, MallocSizeOf)]
pub(crate) struct EventFlows {
    /// Every flow the event belongs to, in any role.
    pub(crate) member_of: Vec<FlowId>,
    /// The flows the event opens.
    pub(crate) starts: Vec<FlowId>,
    /// The flows the event closes.
    pub(crate) ends: Vec<FlowId>,
}

/// The registered flows and the event-to-flow index.
///
/// Built once at init and never modified afterwards.
#[derive(Debug, Default, MallocSizeOf)]
pub(crate) struct FlowRegistry {
    /// Registered flows, sorted by name. A [`FlowId`] indexes into this.
    flows: Vec<RegisteredFlow>,
    /// Event identifier to the flows that event takes part in.
    index: HashMap<String, EventFlows>,
}

impl FlowRegistry {
    /// Builds the registry from the definitions passed in through the configuration.
    ///
    /// Definitions are walked in name order, so every list in the index comes
    /// out in name order without sorting at record time. glean_parser rejects
    /// duplicate flow names; if one gets through anyway, the first definition
    /// wins and the rest are ignored.
    ///
    /// Takes a borrow because `Glean::new_for_subprocess()` only holds
    /// `&InternalConfiguration`; taking ownership would just move the clone
    /// to the caller. The sort below works on references, so the definitions
    /// themselves are not copied, only the strings the registry keeps.
    pub(crate) fn new(definitions: &[FlowDefinition]) -> Self {
        let mut definitions: Vec<&FlowDefinition> = definitions.iter().collect();
        // Stable, so among duplicates the first one passed in stays first.
        definitions.sort_by(|a, b| a.name.cmp(&b.name));
        definitions.dedup_by(|later, earlier| {
            let duplicate = later.name == earlier.name;
            if duplicate {
                log::error!(
                    "Flow '{}' is defined more than once. Ignoring all but the first definition.",
                    later.name
                );
            }
            duplicate
        });

        let mut flows = Vec::with_capacity(definitions.len());
        let mut index: HashMap<String, EventFlows> = HashMap::new();
        for (i, definition) in definitions.into_iter().enumerate() {
            let id = FlowId(i);
            flows.push(RegisteredFlow {
                name: definition.name.clone(),
                auto_close_timeout_ms: definition.auto_close_timeout_ms,
                disabled: definition.disabled,
            });

            for (event, role) in &definition.events {
                let entry = index.entry(event.clone()).or_default();
                entry.member_of.push(id);
                match role {
                    FlowRole::Start => entry.starts.push(id),
                    FlowRole::End => entry.ends.push(id),
                    FlowRole::Member => {}
                }
            }
        }

        Self { flows, index }
    }

    /// Whether no flows are registered.
    #[cfg(test)]
    pub(crate) fn is_empty(&self) -> bool {
        self.flows.is_empty()
    }

    /// Looks up the flows an event metric takes part in.
    ///
    /// When no flows are registered this is a single emptiness check, made before
    /// building the metric's identifier, which is all the recording path pays in
    /// a product that defines no flows.
    pub(crate) fn lookup_metric(&self, meta: &CommonMetricDataInternal) -> Option<&EventFlows> {
        if self.index.is_empty() {
            return None;
        }
        self.index.get(&meta.base_identifier())
    }

    /// Looks up the flows an event takes part in, by its base identifier.
    #[cfg(test)]
    pub(crate) fn lookup(&self, identifier: &str) -> Option<&EventFlows> {
        if self.index.is_empty() {
            return None;
        }
        self.index.get(identifier)
    }

    /// Returns a registered flow.
    pub(crate) fn flow(&self, id: FlowId) -> &RegisteredFlow {
        &self.flows[id.0]
    }

    /// Finds a registered flow by name.
    // TODO(bug 2077143): restoring persisted instances finds their flow by name.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn find(&self, name: &str) -> Option<FlowId> {
        self.flows
            .binary_search_by(|flow| flow.name.as_str().cmp(name))
            .ok()
            .map(FlowId)
    }
}

/// The flow instances active in the current session.
#[derive(Debug, Default)]
pub(crate) struct FlowState {
    /// Each active flow, mapped to its instance's `flow_seq`.
    pub(crate) active: BTreeMap<FlowId, u64>,
}

/// Returns a `flows` entry for every active instance of a flow the event belongs to.
///
/// Entries are in name order, which `member_of` already is.
pub(crate) fn active_entries(glean: &Glean, meta: &CommonMetricDataInternal) -> Vec<FlowEntry> {
    let Some(event_flows) = glean.flow_registry.lookup_metric(meta) else {
        return Vec::new();
    };
    let state = glean.flow_state.lock().unwrap();
    event_flows
        .member_of
        .iter()
        .filter_map(|id| {
            state.active.get(id).map(|seq| FlowEntry {
                name: glean.flow_registry.flow(*id).name.clone(),
                seq: *seq,
            })
        })
        .collect()
}

#[cfg(test)]
mod test {
    use super::*;
    use crate::metrics::EventMetric;
    use crate::session::SessionMode;
    use crate::{CommonMetricData, InternalConfiguration, Lifetime};

    fn definition(name: &str, events: &[(&str, FlowRole)]) -> FlowDefinition {
        FlowDefinition {
            name: name.into(),
            events: events.iter().map(|(e, r)| (e.to_string(), *r)).collect(),
            auto_close_timeout_ms: None,
            disabled: false,
        }
    }

    fn names(registry: &FlowRegistry, ids: &[FlowId]) -> Vec<String> {
        ids.iter()
            .map(|id| registry.flow(*id).name.clone())
            .collect()
    }

    #[test]
    fn no_definitions_gives_an_empty_registry() {
        let registry = FlowRegistry::new(&[]);
        assert!(registry.is_empty());
        assert!(registry.index.is_empty());
        assert!(registry.lookup("onboarding.started").is_none());
        assert!(registry.find("onboarding").is_none());
    }

    #[test]
    fn index_records_membership_and_boundary_roles() {
        let registry = FlowRegistry::new(&[definition(
            "onboarding",
            &[
                ("onboarding.started", FlowRole::Start),
                ("onboarding.finished", FlowRole::End),
                ("onboarding.card_shown", FlowRole::Member),
            ],
        )]);
        let onboarding = registry.find("onboarding").unwrap();

        let started = registry.lookup("onboarding.started").unwrap();
        assert_eq!(vec![onboarding], started.member_of);
        assert_eq!(vec![onboarding], started.starts);
        assert!(started.ends.is_empty());

        let finished = registry.lookup("onboarding.finished").unwrap();
        assert_eq!(vec![onboarding], finished.member_of);
        assert!(finished.starts.is_empty());
        assert_eq!(vec![onboarding], finished.ends);

        let card_shown = registry.lookup("onboarding.card_shown").unwrap();
        assert_eq!(vec![onboarding], card_shown.member_of);
        assert!(card_shown.starts.is_empty());
        assert!(card_shown.ends.is_empty());

        assert!(registry.lookup("settings.opened").is_none());
    }

    #[test]
    fn index_lists_are_in_name_order_regardless_of_definition_order() {
        let shared = "app.opened";
        let registry = FlowRegistry::new(&[
            definition("zeta", &[(shared, FlowRole::Start)]),
            definition("alpha", &[(shared, FlowRole::Member)]),
            definition("mu", &[(shared, FlowRole::Start)]),
        ]);

        let flows = registry.lookup(shared).unwrap();
        assert_eq!(
            vec!["alpha", "mu", "zeta"],
            names(&registry, &flows.member_of)
        );
        assert_eq!(vec!["mu", "zeta"], names(&registry, &flows.starts));
        assert!(flows.ends.is_empty());
    }

    #[test]
    fn duplicate_flow_names_keep_the_first_definition() {
        let mut first = definition("onboarding", &[("onboarding.started", FlowRole::Start)]);
        first.auto_close_timeout_ms = Some(1000);
        let second = definition("onboarding", &[("other.started", FlowRole::Start)]);

        let registry = FlowRegistry::new(&[first, second]);
        let id = registry.find("onboarding").unwrap();
        assert_eq!(Some(1000), registry.flow(id).auto_close_timeout_ms);
        assert!(registry.lookup("onboarding.started").is_some());
        assert!(registry.lookup("other.started").is_none());
    }

    #[test]
    fn registered_flow_carries_its_settings() {
        let mut def = definition("onboarding", &[("onboarding.started", FlowRole::Start)]);
        def.auto_close_timeout_ms = Some(45 * 60 * 1000);
        def.disabled = true;

        let registry = FlowRegistry::new(&[def]);
        let flow = registry.flow(registry.find("onboarding").unwrap());
        assert_eq!("onboarding", flow.name);
        assert_eq!(Some(45 * 60 * 1000), flow.auto_close_timeout_ms);
        assert!(flow.disabled);
    }

    // -----------------------------------------------------------------------
    // Tagging recorded events
    // -----------------------------------------------------------------------

    fn glean_with_flows(flows: Vec<FlowDefinition>) -> (Glean, tempfile::TempDir) {
        let dir = tempfile::tempdir().unwrap();
        let cfg = InternalConfiguration {
            data_path: dir.path().display().to_string(),
            application_id: "org.mozilla.glean.test.app".into(),
            language_binding_name: "Rust".into(),
            upload_enabled: true,
            max_events: None,
            delay_ping_lifetime_io: false,
            app_build: "Unknown".into(),
            use_core_mps: false,
            trim_data_to_registered_pings: false,
            log_level: None,
            rate_limit: None,
            enable_event_timestamps: false,
            experimentation_id: None,
            enable_internal_pings: true,
            ping_schedule: Default::default(),
            ping_lifetime_threshold: 0,
            ping_lifetime_max_time: 0,
            max_pending_pings_count: None,
            max_pending_pings_directory_size: None,
            session_mode: SessionMode::Manual,
            session_sample_rate: 1.0,
            session_inactivity_timeout_ms: 0,
            events_ping_acceleration_factor: None,
            enable_store_submitted_pings: false,
            flows,
        };
        (Glean::new(cfg).unwrap(), dir)
    }

    fn event(category: &str, name: &str, in_session: bool) -> EventMetric {
        EventMetric::new(
            CommonMetricData {
                category: category.into(),
                name: name.into(),
                send_in_pings: vec!["events".into()],
                lifetime: Lifetime::Ping,
                in_session,
                ..Default::default()
            },
            vec![],
        )
    }

    /// Marks `flow` as having an active instance with the given `flow_seq`.
    fn activate(glean: &Glean, flow: &str, seq: u64) {
        let id = glean.flow_registry.find(flow).unwrap();
        glean.flow_state.lock().unwrap().active.insert(id, seq);
    }

    /// Records `metric` and returns the `flows` on the resulting event.
    fn record_and_get_flows(glean: &Glean, metric: &EventMetric) -> Vec<FlowEntry> {
        metric.record_sync(glean, 0, HashMap::new(), 0);
        metric
            .get_value(glean, "events")
            .expect("event should be recorded")
            .pop()
            .unwrap()
            .flows
    }

    fn entry(name: &str, seq: u64) -> FlowEntry {
        FlowEntry {
            name: name.into(),
            seq,
        }
    }

    fn onboarding_and_checkout() -> Vec<FlowDefinition> {
        vec![
            definition(
                "onboarding",
                &[
                    ("onboarding.started", FlowRole::Start),
                    ("app.card_shown", FlowRole::Member),
                    ("app.settings_toggled", FlowRole::Member),
                ],
            ),
            definition(
                "checkout",
                &[
                    ("checkout.started", FlowRole::Start),
                    ("app.card_shown", FlowRole::Member),
                ],
            ),
        ]
    }

    #[test]
    fn member_event_is_tagged_with_its_active_flow() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        activate(&glean, "onboarding", 0);

        let flows = record_and_get_flows(&glean, &event("app", "settings_toggled", true));
        assert_eq!(vec![entry("onboarding", 0)], flows);
    }

    #[test]
    fn member_event_is_not_tagged_when_its_flow_is_not_active() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        // checkout is active, but settings_toggled belongs only to onboarding.
        activate(&glean, "checkout", 0);

        let flows = record_and_get_flows(&glean, &event("app", "settings_toggled", true));
        assert!(flows.is_empty());
    }

    #[test]
    fn event_in_several_active_flows_has_entries_in_name_order() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        activate(&glean, "onboarding", 1);
        activate(&glean, "checkout", 0);

        let flows = record_and_get_flows(&glean, &event("app", "card_shown", true));
        assert_eq!(vec![entry("checkout", 0), entry("onboarding", 1)], flows);
    }

    #[test]
    fn event_named_by_no_flow_is_not_tagged() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        activate(&glean, "onboarding", 0);
        activate(&glean, "checkout", 0);

        let flows = record_and_get_flows(&glean, &event("settings", "opened", true));
        assert!(flows.is_empty());
    }

    #[test]
    fn out_of_session_event_is_not_tagged_even_if_a_flow_names_it() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        activate(&glean, "onboarding", 0);

        let flows = record_and_get_flows(&glean, &event("app", "settings_toggled", false));
        assert!(flows.is_empty());
    }

    #[test]
    fn event_is_not_tagged_between_sessions() {
        let (glean, _t) = glean_with_flows(onboarding_and_checkout());
        activate(&glean, "onboarding", 0);

        let flows = record_and_get_flows(&glean, &event("app", "settings_toggled", true));
        assert!(flows.is_empty());
    }

    #[test]
    fn flows_are_serialized_on_tagged_events_and_omitted_otherwise() {
        let (mut glean, _t) = glean_with_flows(onboarding_and_checkout());
        glean.session_start();
        activate(&glean, "onboarding", 3);

        event("app", "settings_toggled", true).record_sync(&glean, 0, HashMap::new(), 0);
        event("settings", "opened", true).record_sync(&glean, 0, HashMap::new(), 0);

        let json = glean
            .event_storage()
            .snapshot_as_json(&glean, "events", false)
            .unwrap();
        let events = json.as_array().unwrap();
        let find = |category: &str, name: &str| {
            events
                .iter()
                .find(|e| e["category"] == category && e["name"] == name)
                .unwrap()
                .clone()
        };
        assert_eq!(
            serde_json::json!([{"name": "onboarding", "seq": 3}]),
            find("app", "settings_toggled")["flows"]
        );
        assert!(find("settings", "opened").get("flows").is_none());
    }

    #[test]
    fn stored_events_without_flows_deserialize_with_no_flows() {
        let event: crate::event_database::RecordedEvent =
            serde_json::from_str(r#"{"timestamp": 0, "category": "app", "name": "opened"}"#)
                .unwrap();
        assert!(event.flows.is_empty());
    }
}
