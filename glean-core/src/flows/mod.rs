//! Flows: declarative, session-scoped funnel instrumentation.
//!
//! A flow is a named task type declared in `flows.yaml`. glean_parser turns
//! each declaration into a [`FlowDefinition`], which the language binding
//! passes to Glean through its configuration. At init, core inverts those
//! definitions into a [`FlowRegistry`], keyed by event, so the recording path
//! resolves everything it needs about an event with a single lookup.

use std::collections::btree_map::Entry;
use std::collections::{BTreeMap, HashMap};

use chrono::Utc;
use malloc_size_of_derive::MallocSizeOf;
use serde::{Deserialize, Serialize};

use crate::common_metric_data::CommonMetricDataInternal;
use crate::session::EventSessionContext;
use crate::{CommonMetricData, Glean, Lifetime};

/// The role an event plays in a flow.
#[derive(Debug, Clone, Copy, PartialEq, Eq, MallocSizeOf)]
pub enum FlowRole {
    /// Recording the event opens an instance of the flow, if none is active.
    Start,
    /// Recording the event closes the active instance of the flow, if any.
    End,
    /// The event belongs to the flow but does not open or close it.
    Member,
}

/// A flow definition, as generated by glean_parser from `flows.yaml`.
#[derive(Debug, Clone, PartialEq, Eq, MallocSizeOf)]
pub struct FlowDefinition {
    /// The flow's name.
    pub name: String,
    /// Each member event's identifier (`category.name`), mapped to the role it
    /// plays in this flow.
    pub events: HashMap<String, FlowRole>,
    /// How long an instance may stay open before it is closed with
    /// `reason: timeout`, in milliseconds. `None` means it never times out.
    pub auto_close_timeout_ms: Option<u64>,
    /// Whether the flow ships disabled.
    pub disabled: bool,
}

/// An active flow instance an event belongs to, as attached to the recorded event.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize, MallocSizeOf)]
pub struct FlowEntry {
    /// The flow's name.
    pub name: String,
    /// The instance's sequence number within the session, starting at 0.
    pub seq: u64,
}

/// Identifies a registered flow.
///
/// Flows are numbered in name order, so sorting by `FlowId` sorts by name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, MallocSizeOf)]
pub(crate) struct FlowId(usize);

/// A flow as held by the registry.
#[derive(Debug, MallocSizeOf)]
pub(crate) struct RegisteredFlow {
    pub(crate) name: String,
    pub(crate) auto_close_timeout_ms: Option<u64>,
    pub(crate) disabled: bool,
}

/// The flows a single event takes part in.
///
/// Each list is in name order.
#[derive(Debug, Default, PartialEq, Eq, MallocSizeOf)]
pub(crate) struct EventFlows {
    /// Every flow the event belongs to, in any role.
    pub(crate) member_of: Vec<FlowId>,
    /// The flows the event opens.
    pub(crate) starts: Vec<FlowId>,
    /// The flows the event closes.
    pub(crate) ends: Vec<FlowId>,
}

/// The registered flows and the event-to-flow index.
///
/// Built once at init and never modified afterwards.
#[derive(Debug, Default, MallocSizeOf)]
pub(crate) struct FlowRegistry {
    /// Registered flows, sorted by name. A [`FlowId`] indexes into this.
    flows: Vec<RegisteredFlow>,
    /// Event identifier to the flows that event takes part in.
    index: HashMap<String, EventFlows>,
}

impl FlowRegistry {
    /// Builds the registry from the definitions passed in through the configuration.
    ///
    /// Definitions are walked in name order, so every list in the index comes
    /// out in name order without sorting at record time. glean_parser rejects
    /// duplicate flow names; if one gets through anyway, the first definition
    /// wins and the rest are ignored.
    ///
    /// Takes a borrow because `Glean::new_for_subprocess()` only holds
    /// `&InternalConfiguration`; taking ownership would just move the clone
    /// to the caller. The sort below works on references, so the definitions
    /// themselves are not copied, only the strings the registry keeps.
    pub(crate) fn new(definitions: &[FlowDefinition]) -> Self {
        let mut definitions: Vec<&FlowDefinition> = definitions.iter().collect();
        // Stable, so among duplicates the first one passed in stays first.
        definitions.sort_by(|a, b| a.name.cmp(&b.name));
        definitions.dedup_by(|later, earlier| {
            let duplicate = later.name == earlier.name;
            if duplicate {
                log::error!(
                    "Flow '{}' is defined more than once. Ignoring all but the first definition.",
                    later.name
                );
            }
            duplicate
        });

        let mut flows = Vec::with_capacity(definitions.len());
        let mut index: HashMap<String, EventFlows> = HashMap::new();
        for (i, definition) in definitions.into_iter().enumerate() {
            let id = FlowId(i);
            flows.push(RegisteredFlow {
                name: definition.name.clone(),
                auto_close_timeout_ms: definition.auto_close_timeout_ms,
                disabled: definition.disabled,
            });

            for (event, role) in &definition.events {
                let entry = index.entry(event.clone()).or_default();
                entry.member_of.push(id);
                match role {
                    FlowRole::Start => entry.starts.push(id),
                    FlowRole::End => entry.ends.push(id),
                    FlowRole::Member => {}
                }
            }
        }

        Self { flows, index }
    }

    /// Whether no flows are registered.
    #[cfg(test)]
    pub(crate) fn is_empty(&self) -> bool {
        self.flows.is_empty()
    }

    /// Looks up the flows an event metric takes part in.
    ///
    /// When no flows are registered this is a single emptiness check, made before
    /// building the metric's identifier, which is all the recording path pays in
    /// a product that defines no flows.
    pub(crate) fn lookup_metric(&self, meta: &CommonMetricDataInternal) -> Option<&EventFlows> {
        if self.index.is_empty() {
            return None;
        }
        self.index.get(&meta.base_identifier())
    }

    /// Looks up the flows an event takes part in, by its base identifier.
    #[cfg(test)]
    pub(crate) fn lookup(&self, identifier: &str) -> Option<&EventFlows> {
        if self.index.is_empty() {
            return None;
        }
        self.index.get(identifier)
    }

    /// Returns a registered flow.
    pub(crate) fn flow(&self, id: FlowId) -> &RegisteredFlow {
        &self.flows[id.0]
    }

    /// Finds a registered flow by name.
    // TODO(bug 2077143): restoring persisted instances finds their flow by name.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn find(&self, name: &str) -> Option<FlowId> {
        self.flows
            .binary_search_by(|flow| flow.name.as_str().cmp(name))
            .ok()
            .map(FlowId)
    }
}

/// An active flow instance.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ActiveInstance {
    /// The instance's sequence number within the session.
    pub(crate) seq: u64,
    /// When the instance opened, in wall-clock milliseconds since the epoch.
    ///
    /// Wall-clock time so that it stays meaningful across restarts.
    pub(crate) opened_at_ms: i64,
}

/// The flow instances active in the current session.
#[derive(Debug, Default)]
pub(crate) struct FlowState {
    /// Each active flow, mapped to its instance.
    pub(crate) active: BTreeMap<FlowId, ActiveInstance>,
    /// The `flow_seq` the next instance opened in this session will get.
    pub(crate) next_seq: u64,
}

impl FlowState {
    /// Opens an instance of `flow`, unless one is already active.
    ///
    /// An entry event recorded while its flow is active does nothing: the
    /// active instance is kept, not replaced.
    fn open(&mut self, flow: FlowId, now_ms: i64) {
        if let Entry::Vacant(entry) = self.active.entry(flow) {
            entry.insert(ActiveInstance {
                seq: self.next_seq,
                opened_at_ms: now_ms,
            });
            self.next_seq += 1;
        }
    }

    /// Removes and returns every active instance, among `candidates`, whose
    /// flow's `auto_close_timeout` has elapsed since it opened. Returned in
    /// reverse order of opening.
    fn take_expired(
        &mut self,
        registry: &FlowRegistry,
        candidates: &[FlowId],
        now_ms: i64,
    ) -> Vec<(FlowId, u64)> {
        let expired_flows: Vec<FlowId> = candidates
            .iter()
            .copied()
            .filter(|flow| {
                let Some(instance) = self.active.get(flow) else {
                    return false;
                };
                registry
                    .flow(*flow)
                    .auto_close_timeout_ms
                    .is_some_and(|timeout| {
                        let timeout = i64::try_from(timeout).unwrap_or(i64::MAX);
                        now_ms.saturating_sub(instance.opened_at_ms) >= timeout
                    })
            })
            .collect();
        let mut expired: Vec<(FlowId, u64)> = expired_flows
            .into_iter()
            .filter_map(|flow| self.active.remove(&flow).map(|i| (flow, i.seq)))
            .collect();
        expired.sort_by_key(|a| std::cmp::Reverse(a.1));
        expired
    }
}

fn now_ms() -> i64 {
    Utc::now().timestamp_millis()
}

/// Why a flow instance ended, as reported in `glean.flow_end`.
// TODO(bug 2077143): the persistence bug constructs `Abnormal`.
#[allow(dead_code)]
#[derive(Debug, Clone, Copy)]
pub(crate) enum FlowEndReason<'a> {
    /// An event in the flow's `ends_on` was recorded.
    Exit {
        /// The closing event's identifier (`category.name`).
        terminating_event: &'a str,
    },
    /// The flow's `auto_close_timeout` elapsed.
    Timeout,
    /// The session ended while the instance was active.
    SessionEnd,
    /// The app ended abnormally while the instance was active.
    Abnormal {
        /// The session that owned the instance.
        session_id: &'a str,
    },
}

impl FlowEndReason<'_> {
    fn as_str(&self) -> &'static str {
        match self {
            FlowEndReason::Exit { .. } => "exit",
            FlowEndReason::Timeout => "timeout",
            FlowEndReason::SessionEnd => "session_end",
            FlowEndReason::Abnormal { .. } => "abnormal",
        }
    }
}

/// Looks up the flows an event metric's recording can affect.
///
/// Returns `None` unless the metric is in-session and a session is active,
/// since instances only exist within a session: an event recorded between
/// sessions neither opens an instance nor is tagged.
pub(crate) fn lookup<'a>(
    glean: &'a Glean,
    meta: &CommonMetricDataInternal,
) -> Option<&'a EventFlows> {
    if !meta.inner.in_session || !glean.session_manager().is_active() {
        return None;
    }
    glean.flow_registry.lookup_metric(meta)
}

/// Opens an instance of every flow the event starts that has none active.
///
/// Nothing is recorded: the entry event itself is tagged with the new instance.
pub(crate) fn open_instances(glean: &Glean, event_flows: &EventFlows) {
    if event_flows.starts.is_empty() {
        return;
    }
    let now = now_ms();
    let mut state = glean.flow_state.lock().unwrap();
    for flow in &event_flows.starts {
        state.open(*flow, now);
    }
}

/// Closes, with `reason: timeout`, every expired instance of a flow the event
/// belongs to.
///
/// Must be called before the event opens instances or is tagged, so the event
/// that notices an expiry is not tagged with the expired instance, and an entry
/// event for that flow opens a new one in the same recording.
///
/// Returns `true` if any `flow_end` caused a ping to be submitted.
pub(crate) fn close_expired_for_event(glean: &Glean, event_flows: &EventFlows) -> bool {
    close_expired(glean, Some(&event_flows.member_of))
}

/// Closes, with `reason: timeout`, every expired active instance.
///
/// Does nothing when no session is active: instances are only checked, and
/// their `flow_end` only recorded, from within the session that owns them.
///
/// Returns `true` if any `flow_end` caused a ping to be submitted.
pub(crate) fn close_all_expired(glean: &Glean) -> bool {
    if !glean.session_manager().is_active() {
        return false;
    }
    close_expired(glean, None)
}

/// Closes expired instances among `candidates`, or among all active instances
/// when `candidates` is `None`.
fn close_expired(glean: &Glean, candidates: Option<&[FlowId]>) -> bool {
    let expired = {
        let mut state = glean.flow_state.lock().unwrap();
        if state.active.is_empty() {
            return false;
        }
        let all: Vec<FlowId>;
        let candidates = match candidates {
            Some(candidates) => candidates,
            None => {
                all = state.active.keys().copied().collect();
                &all
            }
        };
        state.take_expired(&glean.flow_registry, candidates, now_ms())
    };

    let mut submitted = false;
    for (flow, seq) in expired {
        submitted |= record_flow_end(
            glean,
            &glean.flow_registry.flow(flow).name,
            seq,
            FlowEndReason::Timeout,
        );
    }
    submitted
}

/// Returns a `flows` entry for every active instance of a flow the event belongs to.
///
/// Entries are in name order, which `member_of` already is.
pub(crate) fn active_entries(glean: &Glean, event_flows: &EventFlows) -> Vec<FlowEntry> {
    let state = glean.flow_state.lock().unwrap();
    event_flows
        .member_of
        .iter()
        .filter_map(|id| {
            state.active.get(id).map(|instance| FlowEntry {
                name: glean.flow_registry.flow(*id).name.clone(),
                seq: instance.seq,
            })
        })
        .collect()
}

/// Closes the active instance of every flow the event ends, recording a
/// `glean.flow_end` with `reason: exit` for each.
///
/// Must be called after the event itself is recorded, so each `flow_end` gets
/// a higher `session.event_seq` than the event that closed it.
///
/// Returns `true` if any `flow_end` caused a ping to be submitted.
pub(crate) fn close_instances(
    glean: &Glean,
    event_flows: &EventFlows,
    meta: &CommonMetricDataInternal,
) -> bool {
    if event_flows.ends.is_empty() {
        return false;
    }
    let closed: Vec<(FlowId, u64)> = {
        let mut state = glean.flow_state.lock().unwrap();
        event_flows
            .ends
            .iter()
            .filter_map(|flow| state.active.remove(flow).map(|i| (*flow, i.seq)))
            .collect()
    };
    if closed.is_empty() {
        return false;
    }

    let terminating_event = meta.base_identifier();
    let mut submitted = false;
    for (flow, seq) in closed {
        submitted |= record_flow_end(
            glean,
            &glean.flow_registry.flow(flow).name,
            seq,
            FlowEndReason::Exit {
                terminating_event: &terminating_event,
            },
        );
    }
    submitted
}

/// Closes every active instance with `reason: session_end`, in reverse order of
/// opening, after first closing any that have expired with `reason: timeout`.
///
/// Must be called while the ending session is still current, before its state
/// is torn down and `glean.session_end` is recorded.
pub(crate) fn close_all_at_session_end(glean: &Glean) {
    close_all_expired(glean);
    let mut closed: Vec<(FlowId, u64)> = {
        let mut state = glean.flow_state.lock().unwrap();
        std::mem::take(&mut state.active)
            .into_iter()
            .map(|(flow, instance)| (flow, instance.seq))
            .collect()
    };
    // `flow_seq` is assigned in order of opening.
    closed.sort_by_key(|a| std::cmp::Reverse(a.1));
    for (flow, seq) in closed {
        record_flow_end(
            glean,
            &glean.flow_registry.flow(flow).name,
            seq,
            FlowEndReason::SessionEnd,
        );
    }
}

/// Records a `glean.flow_end` event.
///
/// Like `glean.session_end`, this bypasses `EventMetric` and records directly,
/// but in-session rather than out-of-session, so it is ordered against the
/// instance's own events by `session.event_seq`. It is never flow-tagged. The
/// exception is `reason: abnormal`, recorded at startup before any session
/// exists, which carries the owning session's ID as an extra instead.
///
/// Returns `true` if recording it caused a ping to be submitted.
pub(crate) fn record_flow_end(
    glean: &Glean,
    flow_name: &str,
    flow_seq: u64,
    reason: FlowEndReason,
) -> bool {
    let meta = CommonMetricData {
        name: "flow_end".into(),
        category: "glean".into(),
        send_in_pings: vec!["events".into()],
        lifetime: Lifetime::Ping,
        ..Default::default()
    };

    let mut extra = HashMap::new();
    extra.insert("flow_name".to_string(), flow_name.to_string());
    extra.insert("flow_seq".to_string(), flow_seq.to_string());
    extra.insert("reason".to_string(), reason.as_str().to_string());
    let ctx = match reason {
        FlowEndReason::Exit { terminating_event } => {
            extra.insert(
                "terminating_event".to_string(),
                terminating_event.to_string(),
            );
            glean.session_manager().compute_event_context()
        }
        FlowEndReason::Abnormal { session_id } => {
            extra.insert("session_id".to_string(), session_id.to_string());
            EventSessionContext::OutOfSession
        }
        FlowEndReason::Timeout | FlowEndReason::SessionEnd => {
            glean.session_manager().compute_event_context()
        }
    };
    // Wall-clock time, matching `EventMetric::record`. The event's main
    // timestamp stays on the monotonic clock.
    if glean.with_timestamps() {
        extra.insert(
            "glean_timestamp".to_string(),
            Utc::now().timestamp_millis().to_string(),
        );
    }

    glean.event_storage().record(
        glean,
        &meta.into(),
        crate::get_timestamp_ms(),
        Some(extra),
        ctx,
        Vec::new(),
    )
}

#[cfg(test)]
